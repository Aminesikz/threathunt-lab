"""Run detection D001 on the events and compare the results with the labels.

python -m threathunt_lab evaluate writes reports/evaluation.json and
reports/evaluation.md. Every number comes from actually running detect().
"""

import json
from pathlib import Path

from threathunt_lab.detection import detect
from threathunt_lab.loader import Dataset
from threathunt_lab.schema import get_field

RULE_FILE = "detections/sigma/powershell_encoded_or_download_cradle.yml"


def outcome(expected_alert: bool, alerted: bool) -> str:
    if alerted and expected_alert:
        return "TP"  # true positive: alert, and one was expected
    if alerted:
        return "FP"  # false positive: alert, but none was expected
    if expected_alert:
        return "FN"  # false negative: missed an expected alert
    return "TN"  # true negative: no alert, and none was expected


def ratio(part: int, total: int) -> float | None:
    """part / total rounded to 3 decimals, or None if total is 0."""
    return round(part / total, 3) if total else None


def evaluate(dataset: Dataset) -> dict:
    results = []
    for event in dataset.events:
        alerted = detect(event)  # the detection only sees the event
        label = dataset.label_for(event)  # labels are only used to grade it
        results.append(
            {
                "event_id": get_field(event, "event.id"),
                "scenario_id": label["scenario_id"],
                "classification": label["classification"],
                "expected": label["expected_outcome"],
                "actual": "alert" if alerted else "no_alert",
                "result": outcome(label["expected_outcome"] == "alert", alerted),
                "rationale": label["rationale"],
            }
        )

    counts = {name: 0 for name in ("TP", "FP", "TN", "FN")}
    for row in results:
        counts[row["result"]] += 1

    return {
        "detection": "D001",
        "rule": RULE_FILE,
        "objective": dataset.detection_objective["id"],
        "events": len(results),
        "counts": counts,
        "precision": ratio(counts["TP"], counts["TP"] + counts["FP"]),
        "recall": ratio(counts["TP"], counts["TP"] + counts["FN"]),
        "results": results,
    }


def to_markdown(report: dict) -> str:
    def show(value: float | None) -> str:
        return "n/a" if value is None else str(value)

    counts = report["counts"]
    lines = [
        "# Evaluation: detection D001",
        "",
        "Generated by `python -m threathunt_lab evaluate`. Don't edit by hand.",
        "",
        f"Rule: `{report['rule']}`  ",
        f"Objective: `{report['objective']}`",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Events | {report['events']} |",
        f"| True positives (TP) | {counts['TP']} |",
        f"| False positives (FP) | {counts['FP']} |",
        f"| True negatives (TN) | {counts['TN']} |",
        f"| False negatives (FN) | {counts['FN']} |",
        f"| Precision = TP / (TP + FP) | {show(report['precision'])} |",
        f"| Recall = TP / (TP + FN) | {show(report['recall'])} |",
        "",
        "## Results per event",
        "",
        "| event.id | Scenario | Classification | Expected | Actual | Result |",
        "|---|---|---|---|---|---|",
    ]
    for row in report["results"]:
        lines.append(
            f"| {row['event_id']} | {row['scenario_id']} | {row['classification']} "
            f"| {row['expected']} | {row['actual']} | {row['result']} |"
        )

    lines += ["", "## Misses and false alarms", ""]
    wrong = [row for row in report["results"] if row["result"] in ("FP", "FN")]
    for row in wrong:
        lines.append(f"- **{row['event_id']}** ({row['result']}): {row['rationale']}")
    if not wrong:
        lines.append("None.")

    lines += [
        "",
        "## Assumptions",
        "",
        "- The labels are the answer key for the objective above. `alert` is a positive.",
        "- A `benign` event with an expected `alert` counts as a TP when it alerts: the",
        "  rule did its job, but the activity is legitimate (a benign true positive).",
        f"- {report['events']} hand-made synthetic events. These numbers describe this dataset",
        "  only, not how the rule would perform on a real network.",
        "- The rule was designed from the hunt on these same events, so the results are",
        "  optimistic, like testing on the data you trained on. New, unseen test cases",
        "  would give a fairer picture.",
        "- `detect()` is a Python copy of the Sigma rule. A test checks that its",
        "  patterns match the Sigma file. The Elastic EQL version wasn't run.",
        "- Each event is judged on its own, without looking at other events.",
        "",
    ]
    return "\n".join(lines)


def write_reports(report: dict, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "evaluation.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    (out_dir / "evaluation.md").write_text(to_markdown(report), encoding="utf-8")
